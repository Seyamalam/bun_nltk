import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const compiler = Bun.spawnSync(["rustc", "--version"], { stdout: "pipe", stderr: "pipe" });
if (compiler.exitCode !== 0 || !new TextDecoder().decode(compiler.stdout).startsWith("rustc 1.97.1 ")) {
  throw new Error("nltk compatibility artifact requires pinned rustc 1.97.1");
}
const target = resolve(root, "rust/target/nltk-compat");
const result = Bun.spawnSync(["cargo", "build", "--locked", "--release", "--target", "wasm32-unknown-unknown", "--manifest-path", "rust/compat/Cargo.toml"], {
  cwd: root, env: { ...process.env, CARGO_TARGET_DIR: target, RUSTFLAGS: `--remap-path-prefix=${root}=/bun_nltk` }, stdout: "pipe", stderr: "pipe",
});
if (result.exitCode !== 0) throw new Error(new TextDecoder().decode(result.stderr));
const bytes = readFileSync(resolve(target, "wasm32-unknown-unknown/release/bun_nltk_compat.wasm"));
const sha256 = createHash("sha256").update(bytes).digest("hex");
const source = `// Generated by scripts/build-nltk-compat.ts from rust/compat (no dependencies).\n// SHA-256: ${sha256}\nexport const nltkCompatWasm = "${bytes.toString("base64")}";\n`;
const artifactPath = resolve(root, "src/data/nltk-compat-wasm.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(artifactPath, "utf8") !== source) throw new Error("nltk compatibility WASM does not match Rust sources");
} else writeFileSync(artifactPath, source);
console.log(JSON.stringify({ bytes: bytes.length, sha256 }));
