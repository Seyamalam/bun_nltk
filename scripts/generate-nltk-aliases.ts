import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const indexPath = resolve(root, "index.ts");
const source = readFileSync(indexPath, "utf8");
const api = await import(indexPath) as Record<string, unknown>;
const existing = new Set(Object.keys(api));
const previousAliases = new Set<string>();
const aliasPath = resolve(root, "src/nltk_aliases.ts");
if (existsSync(aliasPath)) {
  for (const match of readFileSync(aliasPath, "utf8").matchAll(/export\s*\{[^}]*\bas\s+([A-Za-z0-9_$]+)\s*\}/g)) {
    previousAliases.add(match[1]!);
  }
}
for (const name of previousAliases) existing.delete(name);
const originals = new Map<string, { original: string; module: string }>();

function add(exported: string, original: string, module: string): void {
  if (!originals.has(exported)) originals.set(exported, { original, module });
}

for (const match of source.matchAll(/export\s*\{([^}]*)\}\s*from\s*["']([^"']+)["']/g)) {
  const [, body, module] = match;
  for (const raw of body!.split(",")) {
    let spec = raw.trim();
    if (!spec || spec.startsWith("//")) continue;
    if (spec.startsWith("type ")) continue;
    spec = spec.replace(/\s+/g, " ");
    const parts = spec.split(" as ");
    const original = parts[0]!.trim();
    const exported = (parts[1] ?? parts[0])!.trim();
    add(exported, original, module!);
  }
}

for (const match of source.matchAll(/export\s*\*\s*from\s*["']([^"']+)["']/g)) {
  const module = match[1]!;
  if (module === "./src/nltk_aliases") continue;
  const loaded = await import(resolve(root, module + ".ts")) as Record<string, unknown>;
  for (const key of Object.keys(loaded)) add(key, key, module);
}

function snake(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
}

const candidates: Array<{ alias: string; original: string; module: string }> = [];
const seen = new Set(existing);
for (const [exported, info] of [...originals].sort(([a], [b]) => a.localeCompare(b))) {
  if (!/^[a-z]/.test(exported) || !/[A-Z]/.test(exported)) continue;
  const alias = snake(exported);
  if (alias === exported || seen.has(alias)) continue;
  seen.add(alias);
  candidates.push({ alias, original: info.original, module: info.module });
}

const lines = [
  "// Generated by scripts/generate-nltk-aliases.ts. Do not edit by hand.",
  "// Python NLTK-style snake_case aliases; camelCase exports remain available.",
  "",
  ...candidates.map(({ alias, original, module }) => {
    const path = module.replace(/^\.\/src\//, "./").replace(/\.ts$/, "");
    return `export { ${original} as ${alias} } from ${JSON.stringify(path)};`;
  }),
  "",
];
writeFileSync(resolve(root, "src/nltk_aliases.ts"), lines.join("\n"));
console.log(JSON.stringify({ aliases: candidates.length, existing: existing.size }));
