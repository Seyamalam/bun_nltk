"""Generate Treebank's Python re Unicode classes, independently of Rust's tables.

Run with the NLTK 3.10.3 oracle's Python 3.14 (Unicode 16.0.0).
"""
import pathlib
import sys
import unicodedata
import regex


def ranges(predicate):
    result = []
    start = previous = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or not predicate(chr(cp)):
            continue
        if previous is None or cp != previous + 1:
            if previous is not None:
                result.append((start, previous))
            start = cp
        previous = cp
    if previous is not None:
        result.append((start, previous))
    return result


def main():
    if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
        raise RuntimeError("requires Python 3.14 with Unicode 16.0.0")
    if regex.__version__ != "2026.9.29":
        raise RuntimeError("requires regex 2026.9.29 (NLTK 3.10.3 RegexpTokenizer backend)")
    rows = ["// Generated by scripts/generate-tokenizer-unicode.py; Python 3.14, Unicode 16.0.0."]
    for name, predicate in [
        ("WORD", lambda char: char.isalnum() or char == "_"),
        ("DECIMAL", lambda char: unicodedata.category(char) == "Nd"),
        ("REGEX_WORD", lambda char: regex.fullmatch(r"\w", char) is not None),
    ]:
        rows.append(f"pub const {name}: &[(u32, u32)] = &[")
        rows.extend(f"    (0x{start:x}, 0x{end:x})," for start, end in ranges(predicate))
        rows.append("];")
    root = pathlib.Path(__file__).resolve().parents[1]
    rows.insert(1, "// REGEX_WORD: regex 2026.9.29 Unicode tables (distinct from Python re).")
    (root / "rust/src/tokenizer_unicode.rs").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
